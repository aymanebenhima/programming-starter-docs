<h2 id="data-types-the-kinds-of-information" tabindex="-1"><a class="header-anchor" href="#data-types-the-kinds-of-information"><span>Data Types: The Kinds of Information</span></a></h2>
<p>In real life, we deal with different kinds of information: words, numbers, and yes/no answers. Programming is exactly the same!</p>
<p>We classify information into different <strong>Data Types</strong>. Here are the most basic ones:</p>
<ul>
<li><strong>Number</strong>: Any number, with or without decimals. Example: <code v-pre>4</code>, <code v-pre>15</code>, <code v-pre>23.42</code>.</li>
<li><strong>String</strong>: Any text, like letters, words, or sentences. You MUST wrap strings in quotes so the computer knows it's text. Example: <code v-pre>&quot;Hello&quot;</code>, <code v-pre>&quot;I love coding&quot;</code>.</li>
<li><strong>Boolean</strong>: This is a simple &quot;on&quot; or &quot;off&quot; switch. It only has two possible values: <code v-pre>TRUE</code> (yes) or <code v-pre>FALSE</code> (no).</li>
</ul>
<h2 id="math-in-pseudo-code" tabindex="-1"><a class="header-anchor" href="#math-in-pseudo-code"><span>Math in Pseudo Code</span></a></h2>
<p>Computers are essentially giant calculators. You can do math in pseudo code using basic symbols:</p>
<ul>
<li>Add: <code v-pre>+</code></li>
<li>Subtract: <code v-pre>-</code></li>
<li>Multiply: <code v-pre>*</code></li>
<li>Divide: <code v-pre>/</code></li>
</ul>
<div class="language-pseudo line-numbers-mode" data-highlighter="prismjs" data-ext="pseudo"><pre v-pre><code><span class="line">PRINT 3 + 4   // Prints 7</span>
