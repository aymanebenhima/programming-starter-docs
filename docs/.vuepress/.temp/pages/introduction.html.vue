<h2 id="what-is-an-algorithm" tabindex="-1"><a class="header-anchor" href="#what-is-an-algorithm"><span>What is an Algorithm?</span></a></h2>
<p>Welcome to the world of programming! If you have zero experience in coding, you are in the right place.</p>
<p>Before we write code for computers, we need to understand how to solve problems. An <strong>Algorithm</strong> is simply a step-by-step list of instructions used to complete a task or solve a problem.</p>
<p>Think of a recipe for baking a cake:</p>
<ol>
<li>Gather ingredients.</li>
<li>Mix the flour and sugar.</li>
<li>Bake in the oven for 30 minutes.</li>
</ol>
<p>If you follow the algorithm perfectly, you get a cake! Computers work the exact same way. They are incredibly fast, but they are not smart. They need <em>you</em> to give them exact, step-by-step instructions.</p>
<h2 id="what-is-pseudo-code" tabindex="-1"><a class="header-anchor" href="#what-is-pseudo-code"><span>What is Pseudo Code?</span></a></h2>
<p><strong>Pseudo Code</strong> (fake code) is a way to write down algorithms using plain human language mixed with some simple structural rules.</p>
<p>Why use it?</p>
<ul>
<li>It ignores strict grammar rules (like missing a semicolon <code v-pre>;</code>).</li>
<li>It helps you focus on <strong>logic</strong> and <strong>problem-solving</strong>.</li>
<li>Once your pseudo code works, it can be easily translated into <em>any</em> real programming language (like Python, JavaScript, or C).</li>
</ul>
<h2 id="the-output-displaying-information" tabindex="-1"><a class="header-anchor" href="#the-output-displaying-information"><span>The Output: Displaying Information</span></a></h2>
<p>When an algorithm runs, we often want it to show us a result. In pseudo code, we use the word <code v-pre>PRINT</code> (or <code v-pre>DISPLAY</code>) to tell the computer to show a message on the screen.</p>
<div class="language-pseudo line-numbers-mode" data-highlighter="prismjs" data-ext="pseudo"><pre v-pre><code><span class="line">PRINT &quot;Hello, World!&quot;</span>
